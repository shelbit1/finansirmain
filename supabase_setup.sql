-- ============================================================================
--  Финансыр · Настройка Supabase (выполнять в SQL Editor)
-- ============================================================================
--
--  ПОРЯДОК ДЕЙСТВИЙ:
--
--  1. Сначала создайте таблицы схемой Prisma:
--         npm run db:push
--     (это создаст все таблицы в схеме public по prisma/schema.prisma)
--
--  2. Затем выполните ЭТОТ скрипт целиком в Supabase → SQL Editor.
--
--  ЗАЧЕМ ЭТО НУЖНО:
--  Приложение работает с базой через Prisma (прямое подключение под ролью-
--  владельцем), которая ОБХОДИТ Row Level Security. Но Supabase дополнительно
--  публикует схему public через авто-API (PostgREST), доступный из браузера по
--  publishable-ключу. Чтобы никто не смог читать/писать данные напрямую через
--  это API, мы включаем RLS на ВСЕХ таблицах БЕЗ политик => для ролей anon и
--  authenticated доступ запрещён, а Prisma продолжает работать как раньше.
--
--  Скрипт идемпотентный — его можно запускать повторно (например, после того
--  как `prisma db push` создаст новые таблицы).
-- ============================================================================

-- 1) Включаем RLS на всех таблицах схемы public (deny-by-default).
do $$
declare
  r record;
begin
  for r in
    select tablename
    from pg_tables
    where schemaname = 'public'
      and tablename <> '_prisma_migrations'
  loop
    execute format('alter table public.%I enable row level security;', r.tablename);
  end loop;
end $$;

-- 2) На всякий случай отзываем прямые гранты у анонимной/авторизованной ролей
--    PostgREST (доступ к данным всё равно идёт только через Prisma на сервере).
do $$
declare
  r record;
begin
  for r in
    select tablename
    from pg_tables
    where schemaname = 'public'
      and tablename <> '_prisma_migrations'
  loop
    execute format(
      'revoke all on table public.%I from anon, authenticated;', r.tablename
    );
  end loop;
end $$;

